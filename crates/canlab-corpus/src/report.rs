//! The generated coverage report, `docs/abimix-coverage.md`.
//!
//! The report is generated, never edited: every number in it came from the run
//! that wrote it, and a capability with no rows has no row here — an absent
//! capability is not 0%, it is unmeasured. Coverage and stress are counted
//! apart, and a refusal is counted apart from both, because declining honestly
//! is not doing the capability.

use std::collections::BTreeMap;
use std::path::Path;

use crate::run::{Provenance, RunReport};

/// Render the report. `generated` is a human-readable timestamp supplied by the
/// caller, so the function itself stays pure and testable.
pub fn render(report: &RunReport, generated: &str) -> String {
    let mut out = String::new();
    out.push_str("# AbiMix coverage\n\n");
    out.push_str(&format!(
        "Generated by `canlab corpus run` on {generated}. Do not edit this file; run the command \
         again.\n\n"
    ));

    out.push_str(&format!("- Backend: `{}`\n", report.backend));
    match &report.tag {
        Some(tag) => out.push_str(&format!(
            "- Filter: `--tag {tag}` — a partial run, not the whole corpus\n"
        )),
        None => out.push_str("- Filter: none (the whole corpus)\n"),
    }
    out.push_str(&match &report.provenance {
        Provenance::Unchecked => String::from(
            "- Provenance: unchecked — the `hf:` rows were not compared with their datasets; \
             run with `--update` to check them\n",
        ),
        Provenance::Checked => String::from(
            "- Provenance: checked — every `hf:` row agreed with its upstream dataset\n",
        ),
        Provenance::Failed(reason) => format!("- Provenance: not checked — {reason}\n"),
    });
    out.push_str(
        "\nCoverage is what the tool must do; stress is what it must survive. A refusal row is \
         counted apart from coverage, because declining honestly is not doing the capability. A \
         capability with no row is unmeasured, not 0%.\n\n",
    );

    out.push_str("| capability | coverage | stress | refusals | pass | fail | unit unchecked |\n");
    out.push_str("|---|---:|---:|---:|---:|---:|---:|\n");

    #[derive(Default)]
    struct Stats {
        coverage: usize,
        stress: usize,
        refusals: usize,
        pass: usize,
        fail: usize,
        unit_unchecked: usize,
    }

    let mut stats: BTreeMap<&str, Stats> = BTreeMap::new();
    for (row, outcome) in &report.rows {
        let entry = stats.entry(row.capability.as_str()).or_default();
        if row.is_refusal() {
            entry.refusals += 1;
        } else if row.is_stress() {
            entry.stress += 1;
        } else {
            entry.coverage += 1;
        }
        match outcome {
            crate::run::Outcome::Pass {
                unit_unchecked, ..
            } => {
                entry.pass += 1;
                if *unit_unchecked {
                    entry.unit_unchecked += 1;
                }
            }
            crate::run::Outcome::Fail { .. } => entry.fail += 1,
        }
    }

    for (capability, stats) in &stats {
        out.push_str(&format!(
            "| `{capability}` | {} | {} | {} | {} | {} | {} |\n",
            stats.coverage,
            stats.stress,
            stats.refusals,
            stats.pass,
            stats.fail,
            stats.unit_unchecked
        ));
    }

    let failures: Vec<_> = report
        .rows
        .iter()
        .filter(|(_, outcome)| !outcome.is_pass())
        .collect();
    if !failures.is_empty() {
        out.push_str("\n## Failures\n\n");
        out.push_str("| file | expected | got |\n|---|---|---|\n");
        for (row, outcome) in failures {
            let mut got = outcome.got().to_string();
            if let crate::run::Outcome::Fail {
                reason: Some(reason), ..
            } = outcome
            {
                got.push_str(&format!(" ({reason})"));
            }
            out.push_str(&format!(
                "| `{}` | {} | {} |\n",
                cell(&crate::row::path_text(&row.path)),
                cell(&row.expect.describe()),
                cell(&got)
            ));
        }
    }

    if !report.load_errors.is_empty() {
        out.push_str("\n## Load errors\n\n");
        out.push_str(
            "These files did not enter the run. The run exits 2 because it cannot be trusted \
             without them.\n\n",
        );
        out.push_str("| file | reason |\n|---|---|\n");
        for error in &report.load_errors {
            out.push_str(&format!(
                "| `{}` | {} |\n",
                cell(&crate::row::path_text(&error.path)),
                cell(&error.reason)
            ));
        }
    }

    out
}

/// Write the report, creating `docs/` if the checkout does not have it yet.
pub fn write(report: &RunReport, generated: &str, path: &Path) -> Result<(), String> {
    if let Some(parent) = path.parent()
        && !parent.as_os_str().is_empty()
    {
        std::fs::create_dir_all(parent)
            .map_err(|error| format!("could not create {}: {error}", parent.display()))?;
    }
    std::fs::write(path, render(report, generated))
        .map_err(|error| format!("could not write {}: {error}", path.display()))
}

/// Make a value safe inside a Markdown table cell.
fn cell(text: &str) -> String {
    text.replace('|', "\\|").replace('\n', " ")
}

#[cfg(test)]
mod tests {
    use super::*;
    use crate::row::{Expect, Row, Subject};
    use crate::run::{Outcome, Provenance};
    use std::path::PathBuf;

    fn row(id: &str, capability: &str, source: &str, expect: Expect, subject: Subject) -> Row {
        Row {
            path: PathBuf::from(format!(
                "tests/cases/{}/{id}.toml",
                subject.as_str()
            )),
            id: id.to_string(),
            subject,
            capability: capability.to_string(),
            source: source.to_string(),
            document: String::from("x + 1 = 3"),
            expect,
            note: None,
        }
    }

    fn pass(got: &str, unit: bool) -> Outcome {
        Outcome::Pass {
            got: got.to_string(),
            unit_unchecked: unit,
        }
    }

    fn fail(got: &str, reason: &str) -> Outcome {
        Outcome::Fail {
            got: got.to_string(),
            reason: Some(reason.to_string()),
        }
    }

    #[test]
    fn groups_by_capability_and_counts_coverage_apart_from_refusals() {
        let report = RunReport {
            rows: vec![
                (
                    row(
                        "a",
                        "solve.quadratic",
                        "https://example.test/paper — 2024, uppgift 1",
                        Expect::Exact("2".into()),
                        Subject::Math,
                    ),
                    pass("\\left\\{2\\right\\}", false),
                ),
                (
                    row(
                        "b",
                        "solve.quadratic",
                        "hf:x/y class#row",
                        Expect::Exact("3".into()),
                        Subject::Math,
                    ),
                    fail("4", "expected 3"),
                ),
                (
                    row(
                        "c",
                        "input.malformed",
                        "docs/corpus.md §1",
                        Expect::Refused("1/0".into()),
                        Subject::Math,
                    ),
                    pass("refused: 1/0", false),
                ),
            ],
            load_errors: Vec::new(),
            backend: String::from("native"),
            tag: None,
            provenance: Provenance::Unchecked,
        };
        let text = render(&report, "2026-11-11 12:00 UTC");
        assert!(text.contains("| `solve.quadratic` | 1 | 1 | 0 | 1 | 1 | 0 |"), "{text}");
        // The refusal row is counted apart from coverage: it is not a coverage
        // row, and it is not a stress row either.
        assert!(text.contains("| `input.malformed` | 0 | 0 | 1 | 1 | 0 | 0 |"), "{text}");
        assert!(text.contains("## Failures"));
        assert!(text.contains("expected 3"), "{text}");
        assert!(text.contains("unchecked"));
    }

    #[test]
    fn an_absent_capability_has_no_row() {
        let report = RunReport {
            rows: vec![(
                row(
                    "a",
                    "solve.linear",
                    "https://example.test/paper — 2024, uppgift 1",
                    Expect::Exact("2".into()),
                    Subject::Math,
                ),
                pass("2", false),
            )],
            load_errors: Vec::new(),
            backend: String::from("native"),
            tag: None,
            provenance: Provenance::Unchecked,
        };
        let text = render(&report, "now");
        assert!(text.contains("solve.linear"));
        assert!(!text.contains("solve.quadratic"));
    }

    #[test]
    fn a_unit_is_reported_as_unchecked_and_not_counted_as_a_failure() {
        let report = RunReport {
            rows: vec![(
                row(
                    "a",
                    "units.sigfigs",
                    "hf:x/y class#row",
                    Expect::Numeric {
                        value: 2.3,
                        tolerance: 0.05,
                        unit: Some(String::from("m")),
                        digits: Some(2),
                    },
                    Subject::Physics,
                ),
                pass("2.3094", true),
            )],
            load_errors: Vec::new(),
            backend: String::from("native"),
            tag: None,
            provenance: Provenance::Checked,
        };
        let text = render(&report, "now");
        assert!(text.contains("| `units.sigfigs` | 0 | 1 | 0 | 1 | 0 | 1 |"), "{text}");
        assert!(text.contains("Provenance: checked"));
    }

    #[test]
    fn a_tagged_run_says_it_is_partial() {
        let report = RunReport {
            rows: Vec::new(),
            load_errors: Vec::new(),
            backend: String::from("native"),
            tag: Some(String::from("solve")),
            provenance: Provenance::Unchecked,
        };
        let text = render(&report, "now");
        assert!(text.contains("partial run"), "{text}");
        assert!(text.contains("--tag solve"));
    }

    #[test]
    fn load_errors_are_listed_and_pipe_characters_are_escaped() {
        let report = RunReport {
            rows: Vec::new(),
            load_errors: vec![crate::row::LoadError {
                path: PathBuf::from("tests/cases/math/bad.toml"),
                reason: String::from("a | b"),
            }],
            backend: String::from("native"),
            tag: None,
            provenance: Provenance::Failed(String::from("network unavailable")),
        };
        let text = render(&report, "now");
        assert!(text.contains("## Load errors"));
        assert!(text.contains("a \\| b"), "{text}");
        assert!(text.contains("Provenance: not checked"));
    }
}
